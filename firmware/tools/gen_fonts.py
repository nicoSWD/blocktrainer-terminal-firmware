#!/usr/bin/env python3
"""Generates src/fonts/*.c and src/fonts/ui_fonts.h: Roboto Medium in the sizes the UI uses.

The UI fonts cover ASCII, Latin-1 (umlauts, degree sign) and a few typographic characters; arrows and
other LV_SYMBOL glyphs come from the Montserrat font of the same size through `fallback`. The big font
(`ui_font_digits`, used for the price, the block height and the clock) holds digits and separators only.
Uncompressed 4 bpp. Needs Pillow; the TTF is in assets/fonts (SIL Open Font License, see OFL-Roboto.txt):
    python3 tools/gen_fonts.py        (from firmware/)
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parent.parent
TTF = root / "assets/fonts/Roboto-Medium.ttf"
OUT = root / "src/fonts"

LATIN = (list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) +
         [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x20AC])
DIGITS = [0x20, 0x25, 0x2B, 0x2C, 0x2D, 0x2E] + list(range(0x30, 0x3B))

# name, pixel size, characters, Montserrat fallback (symbols)
FONTS = [
    ("xs", 14, LATIN, "lv_font_montserrat_14"),
    ("s", 18, LATIN, "lv_font_montserrat_18"),
    ("m", 24, LATIN, "lv_font_montserrat_24"),
    ("l", 28, LATIN, "lv_font_montserrat_28"),
    ("xl", 36, LATIN, "lv_font_montserrat_36"),
    ("2xl", 40, LATIN, "lv_font_montserrat_40"),
    ("3xl", 48, LATIN, "lv_font_montserrat_48"),
    ("digits", 64, DIGITS, None),
]


def runs(codes):
    out, cur = [], [codes[0]]
    for c in codes[1:]:
        if c == cur[-1] + 1:
            cur.append(c)
        else:
            out.append(cur)
            cur = [c]
    out.append(cur)
    return out


def generate(name, size, codes, fallback):
    font = ImageFont.truetype(str(TTF), size)
    ascent, descent = font.getmetrics()
    long_runs = [r for r in runs(codes) if len(r) >= 8]
    rest = [c for r in runs(codes) if len(r) < 8 for c in r]
    groups = long_runs + ([rest] if rest else [])          # one cmap each, glyph ids follow this order

    glyphs, bitmap = [], bytearray()
    for group in groups:
        for code in group:
            ch = chr(code)
            adv = font.getlength(ch)
            x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
            w, h = max(x1 - x0, 0), max(y1 - y0, 0)
            start = len(bitmap)
            if w and h:
                img = Image.new("L", (w, h), 0)
                ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
                px = list(img.getdata())
                for i in range(0, len(px), 2):           # two 4 bit pixels per byte, rows packed back to back
                    bitmap.append((px[i] >> 4) << 4 | ((px[i + 1] >> 4) if i + 1 < len(px) else 0))
            glyphs.append((code, start, round(adv * 16), w, h, x0, -y1))

    rows = ",\n    ".join(", ".join("0x%02X" % b for b in bitmap[i:i + 24]) for i in range(0, len(bitmap), 24))
    dsc = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */"]
    for code, idx, adv, w, h, ox, oy in glyphs:
        dsc.append(f"    {{.bitmap_index = {idx}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, .ofs_x = {ox}, .ofs_y = {oy}}} /* U+{code:04X} */")

    cmaps, lists, gid = [], [], 1
    for n, group in enumerate(groups):
        first, last = group[0], group[-1]
        if len(group) >= 8 and group in long_runs:
            cmaps.append(f"    {{ .range_start = {first}, .range_length = {last - first + 1}, .glyph_id_start = {gid}, "
                         f".unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, "
                         f".type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY }}")
        else:
            lists.append(f"static const uint16_t unicode_list_{n}[] = {{{', '.join(str(c - first) for c in group)}}};")
            cmaps.append(f"    {{ .range_start = {first}, .range_length = {last - first + 1}, .glyph_id_start = {gid}, "
                         f".unicode_list = unicode_list_{n}, .glyph_id_ofs_list = NULL, .list_length = {len(group)}, "
                         f".type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY }}")
        gid += len(group)

    dsc_text = ",\n".join(dsc)
    cmap_text = ",\n".join(cmaps)
    list_text = "\n".join(lists)
    fb = f"&{fallback}" if fallback else "NULL"
    decl = f"extern const lv_font_t {fallback};\n" if fallback else ""
    (OUT / f"ui_font_{name}.c").write_text(f'''// Generated by tools/gen_fonts.py, do not edit. Roboto Medium {size} px (SIL Open Font License, assets/fonts/OFL-Roboto.txt).
#include <lvgl.h>
{decl}
static const uint8_t glyph_bitmap[] = {{
    {rows}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{dsc_text}
}};

{list_text}

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
{cmap_text}
}};

static lv_font_fmt_txt_glyph_cache_t cache;
static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = {len(cmaps)},
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0,
    .cache = &cache
}};

const lv_font_t ui_font_{name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -{max(size // 14, 1)},
    .underline_thickness = {max(size // 16, 1)},
    .dsc = &font_dsc,
    .fallback = {fb}
}};
''')
    print(f"ui_font_{name}: {size} px, {len(glyphs)} glyphs, {len(bitmap)} bytes")


def main():
    OUT.mkdir(exist_ok=True)
    for f in FONTS:
        generate(*f)
    decls = "\n".join(f"extern const lv_font_t ui_font_{n};" for n, *_ in FONTS)
    (OUT / "ui_fonts.h").write_text(f'''// Generated by tools/gen_fonts.py, do not edit. Picked up by ui_internal.h when it exists.
#pragma once
#include <lvgl.h>
#ifdef __cplusplus
extern "C" {{
#endif
{decls}
#ifdef __cplusplus
}}
#endif

#define FONT_XS   (&ui_font_xs)
#define FONT_S    (&ui_font_s)
#define FONT_M    (&ui_font_m)
#define FONT_L    (&ui_font_l)
#define FONT_XL   (&ui_font_xl)
#define FONT_2XL  (&ui_font_2xl)
#define FONT_3XL  (&ui_font_3xl)
#define FONT_HUGE (&ui_font_digits)     // digits and separators only: never put letters in it
#define FONT_PRICE (&ui_font_digits)
''')


main()
